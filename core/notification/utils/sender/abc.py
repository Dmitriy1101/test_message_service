from abc import ABC, abstractmethod
from notification.utils.dataclass import UserDelivery


class SenderABC(ABC):
    """
    Абстрактный базовый класс для реализации отправителей уведомлений.

    Определяет общий интерфейс и шаблонный метод для отправки уведомлений
    через различные каналы связи (Telegram, Email, SMS, etc.).

    Паттерн: Template Method - основной алгоритм отправки фиксирован в send_notification(),
    while конкретные шаги реализации делегируются дочерним классам.

    Sequence Diagram:
        send_notification()
            │
            ├── _get_contact()     # Извлечение контактов
            │
            ├── _send()            # Отправка через сервис
            │
            └── set_status()       # Обновление статусов
    """

    def send_notification(
        self, subject: str, message: str, users: list[UserDelivery]
    ) -> list[UserDelivery]:
        """
        Основной метод отправки уведомлений (Template Method).

        Реализует общий алгоритм отправки уведомлений:
          1. Извлечение контактов из данных пользователей
          2. Отправка сообщения через внешний сервис
          3. Обновление статусов доставки пользователей

        Args:
            subject (str): Заголовок уведомления. Должен быть кратким и информативным.
            message (str): Текст сообщения для отправки. Может содержать форматирование,
                          если это поддерживается конкретным каналом связи.
            users (list[UserDelivery]): Список пользователей для отправки уведомлений.
                                       Каждый пользователь содержит контактные данные
                                       и статус доставки.

        Returns:
            list[UserDelivery]: Обновленный список пользователей с актуальными статусами
                               доставки. Пользователи, которым сообщение было успешно
                               отправлено, помечаются delivered=True.

        Raises:
            Зависит от реализации в дочерних классах.
        """

        sucsess: list[str] = self._send(
            subject=subject, message=message, contacts=self._get_contact(users=users)
        )
        return self.set_status(sucsess=sucsess, users=users)

    @abstractmethod
    def _send(self, subject: str, message: str, contacts: list[str]) -> list[str]:
        """
        Отправляет уведомление через сторонний сервис (абстрактный метод).

        Дочерние классы должны реализовать логику взаимодействия с конкретным
        сервисом отправки (Telegram API, SMTP сервер, SMS шлюз, etc.).

        Args:
            subject (str): Заголовок уведомления. Может использоваться как тема письма,
                          заголовок push-уведомления и т.д.
            message (str): Основной текст сообщения для отправки.
            contacts (list[str]): Список контактов для отправки. Формат контактов
                                 зависит от канала связи (email, phone, username, etc.).

        Returns:
            list[str]: Список успешно отправленных контактов. Должен содержать только
                      те контакты, на которые сообщение было доставлено без ошибок.

        Raises:
            Конкретные исключения зависят от реализации, но должны включать:
            - ServiceSpecificError: Ошибки конкретного сервиса отправки
            - NetworkError: Проблемы с сетевым соединением
            - RateLimitError: Превышение лимитов отправки

        Note:
            Метод должен быть идемпотентным при возможности и корректно обрабатывать
            частичные сбои (часть сообщений отправлена, часть - нет).
        """

    @abstractmethod
    def set_status(
        self, sucsess: list[str], users: list[UserDelivery]
    ) -> list[UserDelivery]:
        """
        Обновляет статусы доставки уведомлений для пользователей.

        Сопоставляет список успешно отправленных контактов с исходным списком
        пользователей и обновляет флаги доставки.

        Args:
            sucsess (list[str]): Список контактов, на которые уведомление было
                                успешно доставлено. Должен соответствовать формату
                                контактов, возвращаемых _get_contact().
            users (list[UserDelivery]): Исходный список пользователей, которым
                                       предназначалось уведомление.

        Returns:
            list[UserDelivery]: Список пользователей с обновленными статусами:
                               - delivered=True для пользователей из списка success
                               - delivered=False для остальных пользователей

        """

    @abstractmethod
    def _get_contact(self, users: list[UserDelivery]) -> list[str]:
        """
        Извлекает контактные данные из списка пользователей.

        Фильтрует пользователей и преобразует их контактную информацию в формат,
        пригодный для использования в методе _send().

        Args:
            users (list[UserDelivery]): Список пользователей с контактной информацией.

        Returns:
            list[str]: Список контактов в формате, ожидаемом конкретным сервисом
                      отправки. Например:
                      - Для Email: ['user@example.com', 'test@domain.com']
                      - Для Telegram: ['@username', 'https://t.me/username']
                      - Для SMS: ['+79123456789', '+79098765432']

        Note:
            Метод должен корректно обрабатывать случаи отсутствия контактных данных.
        """
